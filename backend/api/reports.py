"""FastAPI router for retrieving mentor reports.
Endpoint:
- GET /api/reports/{assessment_id} – returns the report JSON object generated by ``report_service``.
"""

from __future__ import annotations

import json
from fastapi import APIRouter, HTTPException
from loguru import logger

from ..services.report_service import generate_report
from ..db.database import get_db

router = APIRouter()


@router.get("/reports/{assessment_id}", summary="Retrieve mentor report for an assessment")
async def get_report(assessment_id: int):
    """Fetch the stored report from the DB; if missing, generate it on-the-fly."""
    from ..db.database import ReportRecord, EvaluationRecord, AnswerRecord, QuestionRecord

    with get_db() as db:
        report = db.query(ReportRecord).filter_by(assessment_id=assessment_id).first()
        if report:
            try:
                parsed_report = json.loads(report.content)
            except Exception:
                parsed_report = {"raw": report.content}
            return {"assessment_id": assessment_id, "report": parsed_report}

        evals = (
            db.query(EvaluationRecord)
            .join(AnswerRecord, EvaluationRecord.answer_id == AnswerRecord.id)
            .join(QuestionRecord, AnswerRecord.question_id == QuestionRecord.id)
            .filter(QuestionRecord.assessment_id == assessment_id)
            .all()
        )
        if not evals:
            raise HTTPException(status_code=404, detail="No evaluations found for assessment")

        from ..schemas.evaluation import EvaluationResult

        evaluation_results = []
        for ev in evals:
            evaluation_results.append(
                EvaluationResult(
                    score=ev.score,
                    max_score=ev.max_score,
                    feedback=ev.feedback,
                    missing_concepts=ev.missing_concepts.split(",") if ev.missing_concepts else [],
                    misconceptions=ev.misconceptions.split(",") if ev.misconceptions else [],
                    follow_up_question=ev.follow_up_question,
                    uncertainty=ev.uncertainty,
                )
            )

        report_json = generate_report(assessment_id, evaluation_results)
        new_rec = ReportRecord(assessment_id=assessment_id, content=report_json)
        db.add(new_rec)
        db.commit()
        return {"assessment_id": assessment_id, "report": json.loads(report_json)}
